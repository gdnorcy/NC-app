// 按风格生成区块（图片/链接置空）；风格1 返回空数组
export function cubeBlocksForStyle(styleType) {
  const lay = CUBE_LAYOUTS[styleType] || CUBE_LAYOUTS[1];
  if (!lay.blocks) return [];
  return lay.blocks.map((b) => ({ ...b, url: '', link: '' }));
}
